export function statusLabel(value: string | null | undefined, locale: Locale) {
  if (!value) return "-";

  const normalized = value.toLowerCase().replace(/[\s_-]+/g, "");
  const key = statusAliases[normalized] ?? statusAliases[value.toLowerCase()];

  return key ? dictionaries[locale].status[key] : value;
}
